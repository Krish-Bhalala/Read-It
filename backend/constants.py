from enum import IntEnum
from typing import Callable, Any, TypedDict


class HTTPStatus(IntEnum):
    """
    Defines common HTTP status codes as an enumeration of integers.
    """

    OK = 200
    CREATED = 201
    BAD_REQUEST = 400
    UNAUTHORIZED = 401
    FORBIDDEN = 403
    NOT_FOUND = 404
    METHOD_NOT_ALLOWED = 405
    CONFLICT = 409
    INTERNAL_ERROR = 500
    RATE_LIMITED = 429

    @property
    def reason(self) -> str:
        """
        Returns a human-readable reason phrase for the status code.

        :returns: The status code name with underscores replaced by spaces.
        """
        return self.name.replace("_", " ")


# Standard HTTP end-of-line marker
END_OF_LINE = "\r\n"
