STATIC_DIR = "static"

# Common type hints for the server components


class RequestDictType(TypedDict):
    """
    Defines the structure of a parsed HTTP request dictionary.
    """

    method: str  # HTTP method (e.g., GET, POST)
    path: str  # Requested path (e.g., /api/user)
    query: dict[str, str]  # Query parameters
    headers: dict[str, str]  # Request headers
    body: str  # Request body content


class HTTPResponseType(TypedDict, total=False):
    """
    Defines the structure of a response dictionary generated by a handler.
    'total=False' means all fields are optional.
    """

    status: HTTPStatus  # The HTTP status code
    header: dict[str, Any]  # Response headers
    body: str  # Response body content (usually string or JSON string)


# Type for the function used by the handler to send the final response back to the client
SenderFunctionType = Callable[[HTTPResponseType], None]

HandlerFunctionType = Callable[[RequestDictType, SenderFunctionType], HTTPResponseType]
"""
Defines the type signature for all request handler functions.
Accepts a request dictionary and a sender function, and returns an HTTPResponseType dictionary.
"""
